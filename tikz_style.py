"""Conventions of the paper's pgfplots figures and LaTeX tables, shared by the
simulations and the application: the colours of the estimators, the axis and
legend styles, and the writer that puts a fragment into the paper.

Every figure is a bare `\\begin{tikzpicture} ... \\end{tikzpicture}` fragment
that the paper `\\input`s (Main.tex loads tikz with arrows.meta and calc, and
pgfplots 1.18 with the groupplots and fillbetween libraries). A fragment is
written next to the data it is drawn from and, when the environment variable
PAPER_DIR names the paper's source directory, also copied into it.
"""

from __future__ import annotations

import math
import os
import shutil
from pathlib import Path
from typing import Iterable

# One colour per role: the certified estimator, the classical competitor, a certified
# estimator with a pair the graphical criterion disqualifies, and the correctly
# specified bridge. The application uses the first three for the certified OLS,
# naive OLS and the proximal bridge.
COLORS = {
    "certified": "#2a78d6",
    "classical": "#eb6834",
    "disqualified": "#1baf7a",
    "repaired": "#4a3aa7",
}
TEX_COLORS = {
    "appblue": COLORS["certified"],
    "apporange": COLORS["classical"],
    "appgreen": COLORS["disqualified"],
    "appviolet": COLORS["repaired"],
    "appgrey": "#8a8a8a",
    "applight": "#cccccc",
}
COLOR_DEFINITIONS = "".join(
    f"\\definecolor{{{name}}}{{HTML}}{{{hex_color[1:].upper()}}}\n" for name, hex_color in TEX_COLORS.items()
)

# Light grid and frame, small fonts.
AXIS_STYLE = (
    "grid style={applight!50}, axis line style={applight}, tick style={applight},\n"
    "  tick label style={font=\\footnotesize}, label style={font=\\small},\n"
    "  title style={font=\\small, yshift=-3pt}"
)
# A frameless horizontal legend below the axis, entries separated by a little space.
LEGEND_STYLE = (
    "draw=none, fill=none, font=\\footnotesize, legend cell align=left,\n"
    "  /tikz/every even column/.append style={column sep=0.45cm}"
)


def color_name(hex_color: str) -> str:
    """The TikZ name of one of the role colours (`\\definecolor`d in every fragment)."""
    for name, value in TEX_COLORS.items():
        if value.lower() == hex_color.lower():
            return name
    raise KeyError(f"{hex_color} is not one of the figure colours")


def _num(x: float, digits: int) -> str:
    return str(int(x)) if float(x).is_integer() and abs(x) < 1e12 else f"{x:.{digits}g}"


def coordinates(xs: Iterable[float], ys: Iterable[float], digits: int = 6) -> str:
    return " ".join(f"({_num(x, digits)},{_num(y, digits)})" for x, y in zip(xs, ys))


def tickten(values: Iterable[float]) -> str:
    """Every power of ten from the smallest to the largest value, for `ytickten`."""
    vals = [v for v in values if v > 0]
    lo, hi = math.floor(math.log10(min(vals))), math.ceil(math.log10(max(vals)))
    return ",".join(str(k) for k in range(lo, hi + 1))


def paper_dir() -> Path | None:
    """The paper's source directory, from the environment variable PAPER_DIR."""
    value = os.environ.get("PAPER_DIR")
    if not value:
        return None
    path = Path(value).expanduser()
    return path if path.is_dir() else None


def write_fragment(path: Path, body: str, generator: str, paper_subdir: str | None = None) -> None:
    """Write `body` to `path` behind a 'generated by' line and, if PAPER_DIR is
    set, copy it to the subdirectory `paper_subdir` of the paper."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"% generated by {generator}; do not edit by hand\n{body}")
    print(f"wrote {path}")
    paper = paper_dir()
    if paper is not None and paper_subdir is not None:
        target = paper / paper_subdir / path.name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(path, target)
        print(f"  copied to {target}")
